def _parse_conditional(data: Mapping[str, Any], world_cls: type["RuleWorldMixin"]) -> "Rule[Any]":
    """
    Parse a conditional rule (typically from option filters).

    AST Format:
        {"type": "conditional", "test": {...}, "if_true": {...}, "if_false": {...}}

    This is complex because option filters in Rule Builder become conditionals in AST format.
    We use the Conditional class to preserve all branches for explain support.
    """
    from rule_builder.rules import True_, Conditional

    test_data = data.get('test', {})
    if_true_data = data.get('if_true', {})
    if_false_data = data.get('if_false', {})

    # Parse all branches
    test_rule = parse_ast_rule(test_data, world_cls) if isinstance(test_data, dict) and test_data else True_()
    if_true_rule = parse_ast_rule(if_true_data, world_cls) if isinstance(if_true_data, dict) and if_true_data else True_()
    if_false_rule = parse_ast_rule(if_false_data, world_cls) if isinstance(if_false_data, dict) and if_false_data else True_()

    # Check if if_false is just True (typical for option-filtered rules)
    if_false_is_true = (
        isinstance(if_false_data, dict) and
        if_false_data.get('type') == 'constant' and
        if_false_data.get('value') is True
    )

    if if_false_is_true:
        # This is an option-filtered rule - parse the if_true branch directly
        # The option filtering will be handled by world options at runtime
        return if_true_rule

    # Return a Conditional rule to preserve all branches for explain support
    return Conditional(test=test_rule, if_true=if_true_rule, if_false=if_false_rule)


def _parse_helper(data: Mapping[str, Any], world_cls: type["RuleWorldMixin"]) -> "Rule[Any]":
    """
    Parse a helper rule (game-specific or custom rules).

    AST Format:
        {"type": "helper", "name": "CustomRule", "args": [...]}

    Helper rules may have been converted from Rule Builder custom rules,
    or may be game-specific logic. Unknown helpers are wrapped in ASTRule
    for explain support.
    """
    from rule_builder.rules import ASTRule

    helper_name = data.get('name', 'Unknown')
    args = data.get('args', [])

    # Check for round-trip metadata
    if data.get('_converted_from_rule_builder'):
        # Try to restore the original Rule Builder format
        original_args = data.get('_original_args', {})
        try:
            rule_class = world_cls.get_rule_cls(helper_name)
            return rule_class.from_dict({
                'rule': helper_name,
                'options': [],
                'args': original_args
            }, world_cls)
        except (ValueError, KeyError, AttributeError):
            pass

    # Try to find a custom rule with this name
    try:
        rule_class = world_cls.get_rule_cls(helper_name)
        # Parse args - they may be constant-wrapped
        parsed_args = {}
        for i, arg in enumerate(args):
            if isinstance(arg, dict):
                if arg.get('type') == 'constant':
                    parsed_args[f'arg{i}'] = arg.get('value')
                else:
                    # Nested rule or complex value
                    parsed_args[f'arg{i}'] = arg
            else:
                parsed_args[f'arg{i}'] = arg

        return rule_class.from_dict({
            'rule': helper_name,
            'options': [],
            'args': parsed_args
        }, world_cls)
    except (ValueError, KeyError, AttributeError):
        # Unknown helper - wrap in ASTRule for explain support
        logger.debug(f"Wrapping unknown helper rule '{helper_name}' in ASTRule")
        return ASTRule(rule_data=dict(data))


def _parse_compare(data: Mapping[str, Any], world_cls: type["RuleWorldMixin"]) -> "Rule[Any]":
    """
    Parse a compare rule (comparison expression).

    AST Format:
        {"type": "compare", "left": {...}, "op": ">=", "right": {...}}

    Common patterns:
    - state.prog_items[player][item_name] >= count -> Has(item_name, count)
    - state.prog_items[player][item_name] > 0 -> Has(item_name, 1)

    For other patterns, we use the Compare class to preserve for explain support.
    """
    from rule_builder.rules import Has, Compare, CountItem

    left_data = data.get('left', {})
    op = data.get('op', '')
    right_data = data.get('right', {})

    # Try to recognize the pattern: state.prog_items[player][item_name] >= count
    item_check = _try_parse_prog_items_check(left_data, op, right_data)
    if item_check is not None:
        return item_check

    # Parse left and right operands for Compare class
    left_value = _parse_compare_operand(left_data, world_cls)
    right_value = _parse_compare_operand(right_data, world_cls)

    # Return a Compare rule to preserve for explain support
    return Compare(left=left_value, op=op, right=right_value)


def _parse_compare_operand(operand: Any, world_cls: type["RuleWorldMixin"]) -> Any:
    """
    Parse a compare operand into a value or Rule.

    Handles constants, state_method calls, and nested rules.
    """
    from rule_builder.rules import CountItem

    if not isinstance(operand, dict):
        return operand

    op_type = operand.get('type')

    if op_type == 'constant':
        return operand.get('value')

    if op_type == 'state_method':
        method = operand.get('method', '')
        args = operand.get('args', [])

        # Handle count method specially
        if method == 'count':
            if args and isinstance(args[0], dict) and args[0].get('type') == 'constant':
                item_name = args[0].get('value', '')
                return CountItem(item_name=item_name)

    # For other types, try parsing as a rule
    try:
        return parse_ast_rule(operand, world_cls)
    except (ValueError, KeyError):
        return operand


def _try_parse_prog_items_check(left: Any, op: str, right: Any) -> "Rule[Any] | None":
    """
    Try to parse a compare expression as a prog_items item check.

    Pattern: state.prog_items[player][item_name] OP count
    """
    from rule_builder.rules import Has

    # Check if right side is a constant (the count)
    if not isinstance(right, dict) or right.get('type') != 'constant':
        return None
    count = right.get('value', 0)

    # Handle >= operator (Has with count)
    if op == '>=':
        item_name = _extract_prog_items_item_name(left)
        if item_name is not None:
            return Has(item_name=item_name, count=count)

    # Handle > operator (Has with count + 1)
    elif op == '>':
        item_name = _extract_prog_items_item_name(left)
        if item_name is not None:
            return Has(item_name=item_name, count=count + 1)

    # Handle == operator with positive count
    elif op == '==' and count > 0:
        item_name = _extract_prog_items_item_name(left)
        if item_name is not None:
            # == count means "has exactly count", approximate as "has at least count"
            return Has(item_name=item_name, count=count)

    return None


def _extract_prog_items_item_name(expr: Any) -> str | None:
    """
    Extract the item name from a prog_items subscript expression.

    Pattern: state.prog_items[player][item_name]

    Returns the item_name string if the pattern matches, None otherwise.
    """
    # Expected structure:
    # {"type": "subscript", "value": {...}, "index": {"type": "constant", "value": "item_name"}}
    if not isinstance(expr, dict) or expr.get('type') != 'subscript':
        return None

    # Get the item name from the outer subscript index
    index = expr.get('index', {})
    if not isinstance(index, dict) or index.get('type') != 'constant':
        return None
    item_name = index.get('value')

    # Check that the inner expression is state.prog_items[player]
    inner = expr.get('value', {})
    if not isinstance(inner, dict) or inner.get('type') != 'subscript':
        return None

    # Check the innermost expression is state.prog_items
    innermost = inner.get('value', {})
    if not isinstance(innermost, dict) or innermost.get('type') != 'attribute':
        return None

    if innermost.get('attr') != 'prog_items':
        return None

    obj = innermost.get('object', {})
    if not isinstance(obj, dict) or obj.get('type') != 'name' or obj.get('name') != 'state':
        return None

    return item_name


def _parse_binary_op(data: Mapping[str, Any], world_cls: type["RuleWorldMixin"]) -> "Rule[Any]":
    """
    Parse a binary_op rule (arithmetic expression).

    AST Format:
        {"type": "binary_op", "left": {...}, "op": "*", "right": {...}}

    Converts to Arithmetic rule for use in Compare expressions.
    """
    from rule_builder.rules import Arithmetic

    left_data = data.get('left', {})
    op = data.get('op', '+')
    right_data = data.get('right', {})

    # Normalize operator names from Python AST
    op_map = {
        'Add': '+', 'Sub': '-', 'Mult': '*', 'Div': '/',
        'FloorDiv': '//', 'Mod': '%', 'Pow': '**',
    }
    op = op_map.get(op, op)

    left = _parse_arithmetic_operand(left_data, world_cls)
    right = _parse_arithmetic_operand(right_data, world_cls)

    return Arithmetic(left=left, op=op, right=right)


def _parse_arithmetic_operand(operand: Any, world_cls: type["RuleWorldMixin"]) -> Any:
    """
    Parse an arithmetic operand into a value or Rule.

    Handles constants, state_method calls (count), and nested binary_ops.
    """
    from rule_builder.rules import CountItem, Arithmetic

    if not isinstance(operand, dict):
        return operand

    op_type = operand.get('type')

    if op_type == 'constant':
        return operand.get('value', 0)

    if op_type == 'state_method':
        method = operand.get('method', '')
        args = operand.get('args', [])

        if method == 'count':
            if args and isinstance(args[0], dict) and args[0].get('type') == 'constant':
                item_name = args[0].get('value', '')
                return CountItem(item_name=item_name)

        if method == 'count_group_unique':
            from rule_builder.rules import HasGroupUnique
            if args and isinstance(args[0], dict) and args[0].get('type') == 'constant':
                group_name = args[0].get('value', '')
                # HasGroupUnique doesn't have get_value, so wrap for now
                # This will evaluate as boolean (True=1, False=0 in Arithmetic)
                return HasGroupUnique(item_name_group=group_name, count=1)

    if op_type == 'binary_op' or op_type == 'binop':
        return _parse_binary_op(operand, world_cls)

    # For other types, try parsing as a rule
    try:
        return parse_ast_rule(operand, world_cls)
    except (ValueError, KeyError):
        return 0  # Default to 0 for unknown operands
