def convert_json_to_python(
    rule: Dict[str, Any],
    state_var: str = 'state',
    indent_size: int = 4
) -> Tuple[str, List[str]]:
    """
    Convert a JSON rule to Python code.

    Args:
        rule: Rule dictionary in AST format
        state_var: Name of the state variable (default: 'state')
        indent_size: Number of spaces per indent level (default: 4)

    Returns:
        Tuple of (python_code, warnings)
    """
    converter = JSONToPython(state_var=state_var, indent_size=indent_size)
    result = converter.convert(rule)
    return result.code, result.warnings + result.errors


def convert_json_to_lambda(
    rule: Dict[str, Any],
    state_var: str = 'state'
) -> Tuple[str, List[str]]:
    """
    Convert a JSON rule to a Python lambda expression.

    Args:
        rule: Rule dictionary in AST format
        state_var: Name of the state variable (default: 'state')

    Returns:
        Tuple of (lambda_code, warnings)
    """
    code, warnings = convert_json_to_python(rule, state_var=state_var)

    # Check if this is a multi-line block
    if '\n' in code:
        # Can't make a simple lambda - wrap in def
        warnings.append("Multi-line code cannot be converted to lambda, using function")
        return f"def rule({state_var}):\n    {code.replace(chr(10), chr(10) + '    ')}", warnings

    return f"lambda {state_var}: {code}", warnings


def convert_json_to_function(
    rule: Dict[str, Any],
    func_name: str = 'rule',
    state_var: str = 'state',
    indent_size: int = 4
) -> Tuple[str, List[str]]:
    """
    Convert a JSON rule to a Python function definition.

    Args:
        rule: Rule dictionary in AST format
        func_name: Name for the function (default: 'rule')
        state_var: Name of the state variable (default: 'state')
        indent_size: Number of spaces per indent level (default: 4)

    Returns:
        Tuple of (function_code, warnings)
    """
    converter = JSONToPython(state_var=state_var, indent_size=indent_size)
    result = converter.convert(rule)

    code = result.code
    warnings = result.warnings + result.errors

    # Check if it's already a block with return
    if code.strip().startswith('return ') or '\n' in code:
        # Multi-statement - just indent
        indented = '\n'.join('    ' + line for line in code.split('\n'))
        return f"def {func_name}({state_var}):\n{indented}", warnings
    else:
        # Single expression - add return
        return f"def {func_name}({state_var}):\n    return {code}", warnings
