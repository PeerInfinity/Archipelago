"""
Converter from Archipelago-CC JSON rule format to Python code.

This module generates Python code from JSON rule structures, supporting all
rule types generated by the analyzer:

- Basic types: constant, item_check, count_check, group_check
- Logic: and, or, not, conditional
- Reachability: can_reach, location_check, can_reach_entrance
- Calls: helper, state_method, method_call, function_call
- References: attribute, name, subscript
- Collections: list, tuple
- Imperative: block, return, assign, for_range, for_iter, if_statement, break, continue
- Generators: all_of, any_of, generator_expression
- Math: binary_op, compare, min, max, negate
- Other: f_string, formatted_value, setting_value, player_id, region_reference, region_attribute

Usage:
    from exporter.converter.json_to_python import convert_json_to_python, JSONToPython

    # Convert a rule to Python code
    python_code = convert_json_to_python(rule_dict)

    # Or use the class directly for more control
    converter = JSONToPython()
    code = converter.convert(rule_dict)
"""

import json
import logging
from typing import Any, Dict, List, Optional, Tuple
from dataclasses import dataclass, field

logger = logging.getLogger(__name__)


@dataclass
class ConversionResult:
    """Result of a rule to Python conversion."""
    code: str
    warnings: List[str] = field(default_factory=list)
    errors: List[str] = field(default_factory=list)

    @property
    def success(self) -> bool:
        return len(self.errors) == 0


class JSONToPython:
    """
    Converter from Archipelago-CC JSON rule format to Python code.

    Supports all rule types generated by the Python→JSON analyzer.
    """

    # Mapping of rule types to converter methods
    TYPE_CONVERTERS = {}

    def __init__(self, state_var: str = 'state', indent_size: int = 4):
        """
        Initialize the converter.

        Args:
            state_var: Name of the state variable (default: 'state')
            indent_size: Number of spaces per indent level (default: 4)
        """
        self.state_var = state_var
        self.indent_size = indent_size
        self.warnings: List[str] = []
        self.errors: List[str] = []
        self._init_converters()

    def _init_converters(self):
        """Initialize the type converter mapping."""
        self.TYPE_CONVERTERS = {
            # Constants and basic types
            'constant': self._convert_constant,

            # Item and group rules
            'item_check': self._convert_item_check,
            'count_check': self._convert_count_check,
            'group_check': self._convert_group_check,
            'group_count': self._convert_group_count,
            'prog_item_count': self._convert_prog_item_count,

            # Boolean logic
            'and': self._convert_and,
            'or': self._convert_or,
            'not': self._convert_not,
            'conditional': self._convert_conditional,

            # Reachability
            'can_reach': self._convert_can_reach,
            'location_check': self._convert_location_check,
            'can_reach_entrance': self._convert_can_reach_entrance,
            'region_reference': self._convert_region_reference,
            'region_attribute': self._convert_region_attribute,

            # Function/method calls
            'helper': self._convert_helper,
            'state_method': self._convert_state_method,
            'method_call': self._convert_method_call,
            'function_call': self._convert_function_call,

            # References
            'attribute': self._convert_attribute,
            'name': self._convert_name,
            'subscript': self._convert_subscript,
            'setting_value': self._convert_setting_value,  # Legacy, kept for backward compat
            'option_value': self._convert_option_value,
            'world_attribute': self._convert_world_attribute,
            'player_id': self._convert_player_id,

            # Collections
            'list': self._convert_list,
            'tuple': self._convert_tuple,

            # Imperative constructs
            'block': self._convert_block,
            'return': self._convert_return,
            'assign': self._convert_assign,
            'for_range': self._convert_for_range,
            'for_iter': self._convert_for_iter,
            'if_statement': self._convert_if_statement,
            'break': self._convert_break,
            'continue': self._convert_continue,

            # Generators
            'all_of': self._convert_all_of,
            'any_of': self._convert_any_of,
            'generator_expression': self._convert_generator_expression,
            'comprehension_details': self._convert_comprehension_details,

            # Math operations
            'binary_op': self._convert_binary_op,
            'compare': self._convert_compare,
            'min': self._convert_min,
            'max': self._convert_max,
            'negate': self._convert_negate,

            # String formatting
            'f_string': self._convert_f_string,
            'formatted_value': self._convert_formatted_value,

            # Error/unknown
            'error': self._convert_error,
            'unknown': self._convert_unknown,
        }

    def convert(self, rule: Dict[str, Any]) -> ConversionResult:
        """
        Convert a JSON rule to Python code.

        Args:
            rule: Rule dictionary in AST format

        Returns:
            ConversionResult with Python code and any warnings/errors
        """
        self.warnings = []
        self.errors = []

        try:
            code = self._convert_rule(rule)
            return ConversionResult(
                code=code,
                warnings=self.warnings.copy(),
                errors=self.errors.copy()
            )
        except Exception as e:
            self.errors.append(f"Conversion failed: {str(e)}")
            return ConversionResult(
                code=f"# Error: {str(e)}\n{repr(rule)}",
                warnings=self.warnings.copy(),
                errors=self.errors.copy()
            )

    def _convert_rule(self, rule: Any, context: str = 'expression') -> str:
        """
        Convert a single rule to Python code.

        Args:
            rule: Rule dictionary or primitive value
            context: 'expression' or 'statement' (affects formatting)

        Returns:
            Python code string
        """
        if rule is None:
            return 'None'

        if not isinstance(rule, dict):
            # Primitive value - convert directly
            return self._convert_primitive(rule)

        rule_type = rule.get('type')
        if not rule_type:
            # Check if it's already a primitive wrapped somehow
            if 'value' in rule:
                return self._convert_primitive(rule['value'])
            self.warnings.append(f"Rule missing 'type' field: {rule}")
            return repr(rule)

        converter = self.TYPE_CONVERTERS.get(rule_type)
        if converter:
            return converter(rule, context)

        # Unknown type
        self.warnings.append(f"Unknown rule type '{rule_type}', generating comment")
        return f"# Unknown type: {rule_type}\n{repr(rule)}"

    def _convert_primitive(self, value: Any) -> str:
        """Convert a primitive Python value to code."""
        if value is None:
            return 'None'
        if isinstance(value, bool):
            return 'True' if value else 'False'
        if isinstance(value, str):
            return repr(value)
        if isinstance(value, (int, float)):
            return str(value)
        if isinstance(value, list):
            items = ', '.join(self._convert_primitive(v) for v in value)
            return f'[{items}]'
        if isinstance(value, dict):
            items = ', '.join(f'{repr(k)}: {self._convert_primitive(v)}' for k, v in value.items())
            return f'{{{items}}}'
        return repr(value)

    def _indent(self, code: str, level: int = 1) -> str:
        """Indent code by the given level."""
        indent = ' ' * (self.indent_size * level)
        lines = code.split('\n')
        return '\n'.join(indent + line if line.strip() else line for line in lines)

    def _needs_parens(self, rule: Dict, parent_op: Optional[str] = None) -> bool:
        """Check if a rule needs parentheses based on precedence."""
        rule_type = rule.get('type', '')
        # And has higher precedence than Or, so Or inside And needs parens
        if parent_op == 'and' and rule_type == 'or':
            return True
        # Comparison operators might need parens in complex contexts
        if parent_op in ('and', 'or') and rule_type in ('compare', 'conditional'):
            return rule_type == 'conditional'
        return False

    # -------------------------------------------------------------------------
    # Constant Converters
    # -------------------------------------------------------------------------

    def _convert_constant(self, rule: Dict, context: str) -> str:
        """Convert constant rule."""
        value = rule.get('value')
        return self._convert_primitive(value)

    # -------------------------------------------------------------------------
    # Item and Group Rule Converters
    # -------------------------------------------------------------------------

    def _convert_item_check(self, rule: Dict, context: str) -> str:
        """Convert item_check rule to state.has() call."""
        item = rule.get('item', '')
        count = rule.get('count', 1)

        # Handle complex item references
        if isinstance(item, dict):
            item_code = self._convert_rule(item)
        else:
            item_code = repr(item)

        if count != 1:
            return f"{self.state_var}.has({item_code}, {count})"
        return f"{self.state_var}.has({item_code})"

    def _convert_count_check(self, rule: Dict, context: str) -> str:
        """Convert count_check rule to state.count() comparison."""
        item = rule.get('item', '')
        count = rule.get('count', 1)

        if isinstance(item, dict):
            item_code = self._convert_rule(item)
        else:
            item_code = repr(item)

        return f"{self.state_var}.count({item_code}) >= {count}"

    def _convert_group_check(self, rule: Dict, context: str) -> str:
        """Convert group_check rule to state.has_group() call."""
        group = rule.get('group', '')
        count = rule.get('count', 1)

        if count != 1:
            return f"{self.state_var}.has_group({repr(group)}, {count})"
        return f"{self.state_var}.has_group({repr(group)})"

    def _convert_group_count(self, rule: Dict, context: str) -> str:
        """Convert group_count rule to state.count_group() call."""
        group = rule.get('group', '')
        return f"{self.state_var}.count_group({repr(group)})"

    def _convert_prog_item_count(self, rule: Dict, context: str) -> str:
        """Convert prog_item_count rule."""
        item = rule.get('item', '')
        return f"{self.state_var}.count({repr(item)})"

    # -------------------------------------------------------------------------
    # Boolean Logic Converters
    # -------------------------------------------------------------------------

    def _convert_and(self, rule: Dict, context: str) -> str:
        """Convert and rule to Python and expression."""
        conditions = rule.get('conditions', [])

        if not conditions:
            return 'True'

        parts = []
        for cond in conditions:
            code = self._convert_rule(cond)
            if self._needs_parens(cond, 'and'):
                code = f'({code})'
            parts.append(code)

        if len(parts) == 1:
            return parts[0]

        return ' and '.join(parts)

    def _convert_or(self, rule: Dict, context: str) -> str:
        """Convert or rule to Python or expression."""
        conditions = rule.get('conditions', [])

        if not conditions:
            return 'False'

        parts = []
        for cond in conditions:
            code = self._convert_rule(cond)
            if self._needs_parens(cond, 'or'):
                code = f'({code})'
            parts.append(code)

        if len(parts) == 1:
            return parts[0]

        return ' or '.join(parts)

    def _convert_not(self, rule: Dict, context: str) -> str:
        """Convert not rule to Python not expression."""
        condition = rule.get('condition', {})
        code = self._convert_rule(condition)

        # Check if we need parens
        cond_type = condition.get('type', '') if isinstance(condition, dict) else ''
        if cond_type in ('and', 'or', 'conditional'):
            return f'not ({code})'
        return f'not {code}'

    def _convert_conditional(self, rule: Dict, context: str) -> str:
        """Convert conditional rule to Python ternary expression."""
        test = rule.get('test', {})
        if_true = rule.get('if_true', {})
        if_false = rule.get('if_false')

        test_code = self._convert_rule(test)
        if_true_code = self._convert_rule(if_true)

        if if_false is None:
            # No else - this is unusual for a ternary, might be from an if statement
            return f'{if_true_code} if {test_code} else None'

        if_false_code = self._convert_rule(if_false)
        return f'{if_true_code} if {test_code} else {if_false_code}'

    # -------------------------------------------------------------------------
    # Reachability Converters
    # -------------------------------------------------------------------------

    def _convert_can_reach(self, rule: Dict, context: str) -> str:
        """Convert can_reach rule to state.can_reach() call."""
        region = rule.get('region', '')
        return f"{self.state_var}.can_reach({repr(region)}, 'Region', {self.state_var}.player)"

    def _convert_location_check(self, rule: Dict, context: str) -> str:
        """Convert location_check rule."""
        location = rule.get('location', '')
        return f"{self.state_var}.can_reach({repr(location)}, 'Location', {self.state_var}.player)"

    def _convert_can_reach_entrance(self, rule: Dict, context: str) -> str:
        """Convert can_reach_entrance rule."""
        entrance = rule.get('entrance', '')
        return f"{self.state_var}.can_reach({repr(entrance)}, 'Entrance', {self.state_var}.player)"

    def _convert_region_reference(self, rule: Dict, context: str) -> str:
        """Convert region_reference rule."""
        region = rule.get('region', '')
        return f"{self.state_var}.multiworld.get_region({repr(region)}, {self.state_var}.player)"

    def _convert_region_attribute(self, rule: Dict, context: str) -> str:
        """Convert region_attribute rule."""
        region = rule.get('region', '')
        attr = rule.get('attr', '')
        return f"{self.state_var}.multiworld.get_region({repr(region)}, {self.state_var}.player).{attr}"

    # -------------------------------------------------------------------------
    # Function/Method Call Converters
    # -------------------------------------------------------------------------

    def _convert_helper(self, rule: Dict, context: str) -> str:
        """Convert helper rule to function call."""
        name = rule.get('name', 'unknown_helper')
        args = rule.get('args', [])

        # Convert arguments
        arg_parts = []
        for arg in args:
            if isinstance(arg, dict):
                arg_parts.append(self._convert_rule(arg))
            else:
                arg_parts.append(self._convert_primitive(arg))

        # Add state as first arg if not already present
        args_str = ', '.join(arg_parts)

        # Check if we need to add state
        if args_str and not args_str.startswith(self.state_var):
            return f'{name}({self.state_var}, {args_str})'
        elif args_str:
            return f'{name}({args_str})'
        else:
            return f'{name}({self.state_var})'

    def _convert_state_method(self, rule: Dict, context: str) -> str:
        """Convert state_method rule to state.method() call."""
        method = rule.get('method', '')
        args = rule.get('args', [])

        # Convert arguments
        arg_parts = []
        for arg in args:
            if isinstance(arg, dict):
                arg_type = arg.get('type', '')
                if arg_type == 'constant':
                    arg_parts.append(self._convert_primitive(arg.get('value')))
                else:
                    arg_parts.append(self._convert_rule(arg))
            else:
                arg_parts.append(self._convert_primitive(arg))

        args_str = ', '.join(arg_parts)
        return f"{self.state_var}.{method}({args_str})"

    def _convert_method_call(self, rule: Dict, context: str) -> str:
        """Convert method_call rule."""
        obj = rule.get('object', {})
        method = rule.get('method', '')
        args = rule.get('args', [])

        obj_code = self._convert_rule(obj)

        arg_parts = []
        for arg in args:
            if isinstance(arg, dict):
                arg_parts.append(self._convert_rule(arg))
            else:
                arg_parts.append(self._convert_primitive(arg))

        args_str = ', '.join(arg_parts)
        return f"{obj_code}.{method}({args_str})"

    def _convert_function_call(self, rule: Dict, context: str) -> str:
        """Convert function_call rule."""
        func = rule.get('function', rule.get('name', 'unknown'))
        args = rule.get('args', [])

        if isinstance(func, dict):
            func_code = self._convert_rule(func)
        else:
            func_code = func

        arg_parts = []
        for arg in args:
            if isinstance(arg, dict):
                arg_parts.append(self._convert_rule(arg))
            else:
                arg_parts.append(self._convert_primitive(arg))

        args_str = ', '.join(arg_parts)
        return f"{func_code}({args_str})"

    # -------------------------------------------------------------------------
    # Reference Converters
    # -------------------------------------------------------------------------

    def _convert_attribute(self, rule: Dict, context: str) -> str:
        """Convert attribute rule to obj.attr expression."""
        obj = rule.get('object', {})
        attr = rule.get('attr', '')

        obj_code = self._convert_rule(obj)
        return f"{obj_code}.{attr}"

    def _convert_name(self, rule: Dict, context: str) -> str:
        """Convert name rule to variable reference."""
        name = rule.get('name', '')
        return name

    def _convert_subscript(self, rule: Dict, context: str) -> str:
        """Convert subscript rule to obj[index] expression."""
        obj = rule.get('object', rule.get('value', {}))
        index = rule.get('index', rule.get('slice', {}))

        obj_code = self._convert_rule(obj)
        index_code = self._convert_rule(index)

        return f"{obj_code}[{index_code}]"

    def _convert_setting_value(self, rule: Dict, context: str) -> str:
        """Convert setting_value rule to options reference (legacy, for backward compat)."""
        setting = rule.get('setting', '')
        return f"world.options.{setting}.value"

    def _convert_option_value(self, rule: Dict, context: str) -> str:
        """Convert option_value rule to options reference."""
        option = rule.get('option', '')
        return f"world.options.{option}.value"

    def _convert_world_attribute(self, rule: Dict, context: str) -> str:
        """Convert world_attribute rule to world attribute reference."""
        attribute = rule.get('attribute', '')
        index = rule.get('index')
        if index is not None:
            return f"world.{attribute}[{index}]"
        return f"world.{attribute}"

    def _convert_player_id(self, rule: Dict, context: str) -> str:
        """Convert player_id rule."""
        return f"{self.state_var}.player"

    # -------------------------------------------------------------------------
    # Collection Converters
    # -------------------------------------------------------------------------

    def _convert_list(self, rule: Dict, context: str) -> str:
        """Convert list rule to Python list."""
        items = rule.get('value', rule.get('items', []))

        item_codes = []
        for item in items:
            if isinstance(item, dict):
                item_codes.append(self._convert_rule(item))
            else:
                item_codes.append(self._convert_primitive(item))

        return f"[{', '.join(item_codes)}]"

    def _convert_tuple(self, rule: Dict, context: str) -> str:
        """Convert tuple rule to Python tuple."""
        items = rule.get('value', rule.get('items', []))

        item_codes = []
        for item in items:
            if isinstance(item, dict):
                item_codes.append(self._convert_rule(item))
            else:
                item_codes.append(self._convert_primitive(item))

        if len(item_codes) == 1:
            return f"({item_codes[0]},)"
        return f"({', '.join(item_codes)})"

    # -------------------------------------------------------------------------
    # Imperative Construct Converters
    # -------------------------------------------------------------------------

    def _convert_block(self, rule: Dict, context: str) -> str:
        """Convert block rule to multiple statements."""
        statements = rule.get('statements', [])

        lines = []
        for stmt in statements:
            code = self._convert_rule(stmt, context='statement')
            lines.append(code)

        return '\n'.join(lines)

    def _convert_return(self, rule: Dict, context: str) -> str:
        """Convert return rule to return statement."""
        value = rule.get('value', {})
        value_code = self._convert_rule(value)
        return f"return {value_code}"

    def _convert_assign(self, rule: Dict, context: str) -> str:
        """Convert assign rule to assignment statement."""
        name = rule.get('name', '_')
        value = rule.get('value', {})
        op = rule.get('op', '=')  # Can be '=', '+=', '-=', etc.

        value_code = self._convert_rule(value)

        if op == '=':
            return f"{name} = {value_code}"
        else:
            return f"{name} {op} {value_code}"

    def _convert_for_range(self, rule: Dict, context: str) -> str:
        """Convert for_range rule to for loop over range().

        Supports:
        - range(count) - old format with 'count' key
        - range(start, stop) - new format with 'start' and 'stop' keys
        - range(start, stop, step) - new format with 'start', 'stop', and 'step' keys
        """
        var = rule.get('var', 'i')
        body = rule.get('body', [])

        # Determine range() arguments
        if 'start' in rule and 'stop' in rule:
            # New format: range(start, stop) or range(start, stop, step)
            start_code = self._convert_rule(rule['start'])
            stop_code = self._convert_rule(rule['stop'])
            if 'step' in rule:
                step_code = self._convert_rule(rule['step'])
                range_code = f"range({start_code}, {stop_code}, {step_code})"
            else:
                range_code = f"range({start_code}, {stop_code})"
        else:
            # Old format: range(count)
            count = rule.get('count', {})
            count_code = self._convert_rule(count)
            range_code = f"range({count_code})"

        body_lines = []
        for stmt in body:
            code = self._convert_rule(stmt, context='statement')
            body_lines.append(self._indent(code))

        body_str = '\n'.join(body_lines) if body_lines else self._indent('pass')
        return f"for {var} in {range_code}:\n{body_str}"

    def _convert_for_iter(self, rule: Dict, context: str) -> str:
        """Convert for_iter rule to for loop over iterable."""
        var = rule.get('var', 'item')
        iterable = rule.get('iterable', {})
        body = rule.get('body', [])

        iterable_code = self._convert_rule(iterable)

        body_lines = []
        for stmt in body:
            code = self._convert_rule(stmt, context='statement')
            body_lines.append(self._indent(code))

        body_str = '\n'.join(body_lines) if body_lines else self._indent('pass')
        return f"for {var} in {iterable_code}:\n{body_str}"

    def _convert_if_statement(self, rule: Dict, context: str) -> str:
        """Convert if_statement rule to if statement."""
        test = rule.get('test', {})
        body = rule.get('body', [])
        orelse = rule.get('orelse', [])

        test_code = self._convert_rule(test)

        body_lines = []
        for stmt in body:
            code = self._convert_rule(stmt, context='statement')
            body_lines.append(self._indent(code))

        body_str = '\n'.join(body_lines) if body_lines else self._indent('pass')
        result = f"if {test_code}:\n{body_str}"

        if orelse:
            orelse_lines = []
            for stmt in orelse:
                code = self._convert_rule(stmt, context='statement')
                orelse_lines.append(self._indent(code))

            orelse_str = '\n'.join(orelse_lines)
            result += f"\nelse:\n{orelse_str}"

        return result

    def _convert_break(self, rule: Dict, context: str) -> str:
        """Convert break rule."""
        return 'break'

    def _convert_continue(self, rule: Dict, context: str) -> str:
        """Convert continue rule."""
        return 'continue'

    # -------------------------------------------------------------------------
    # Generator Converters
    # -------------------------------------------------------------------------

    def _convert_all_of(self, rule: Dict, context: str) -> str:
        """Convert all_of rule to all() expression."""
        element_rule = rule.get('element_rule', {})
        iterable = rule.get('iterable', {})
        var = rule.get('var', 'x')
        condition = rule.get('condition')

        elem_code = self._convert_rule(element_rule)
        iter_code = self._convert_rule(iterable)

        if condition:
            cond_code = self._convert_rule(condition)
            return f"all({elem_code} for {var} in {iter_code} if {cond_code})"
        return f"all({elem_code} for {var} in {iter_code})"

    def _convert_any_of(self, rule: Dict, context: str) -> str:
        """Convert any_of rule to any() expression."""
        element_rule = rule.get('element_rule', {})
        iterable = rule.get('iterable', {})
        var = rule.get('var', 'x')
        condition = rule.get('condition')

        elem_code = self._convert_rule(element_rule)
        iter_code = self._convert_rule(iterable)

        if condition:
            cond_code = self._convert_rule(condition)
            return f"any({elem_code} for {var} in {iter_code} if {cond_code})"
        return f"any({elem_code} for {var} in {iter_code})"

    def _convert_generator_expression(self, rule: Dict, context: str) -> str:
        """Convert generator_expression rule."""
        element = rule.get('element', {})
        generators = rule.get('generators', [])

        elem_code = self._convert_rule(element)

        gen_parts = []
        for gen in generators:
            var = gen.get('var', 'x')
            iterable = gen.get('iterable', {})
            conditions = gen.get('conditions', [])

            iter_code = self._convert_rule(iterable)
            part = f"for {var} in {iter_code}"

            for cond in conditions:
                cond_code = self._convert_rule(cond)
                part += f" if {cond_code}"

            gen_parts.append(part)

        return f"({elem_code} {' '.join(gen_parts)})"

    def _convert_comprehension_details(self, rule: Dict, context: str) -> str:
        """Convert comprehension_details rule."""
        # This is typically used as metadata, not standalone
        return self._convert_generator_expression(rule, context)

    # -------------------------------------------------------------------------
    # Math Operation Converters
    # -------------------------------------------------------------------------

    def _convert_binary_op(self, rule: Dict, context: str) -> str:
        """Convert binary_op rule to Python binary expression."""
        left = rule.get('left', {})
        op = rule.get('op', '+')
        right = rule.get('right', {})

        left_code = self._convert_rule(left)
        right_code = self._convert_rule(right)

        return f"({left_code} {op} {right_code})"

    def _convert_compare(self, rule: Dict, context: str) -> str:
        """Convert compare rule to Python comparison expression."""
        left = rule.get('left', {})
        ops = rule.get('ops', [rule.get('op', '==')])
        comparators = rule.get('comparators', [rule.get('right', {})])

        # Handle single comparison (op/right format)
        if not isinstance(ops, list):
            ops = [ops]
        if not isinstance(comparators, list) or (comparators and not isinstance(comparators[0], dict)):
            comparators = [comparators]

        left_code = self._convert_rule(left)

        parts = [left_code]
        for op, comp in zip(ops, comparators):
            comp_code = self._convert_rule(comp)
            parts.append(f"{op} {comp_code}")

        return ' '.join(parts)

    def _convert_min(self, rule: Dict, context: str) -> str:
        """Convert min rule to min() call."""
        args = rule.get('args', [])

        arg_codes = []
        for arg in args:
            if isinstance(arg, dict):
                arg_codes.append(self._convert_rule(arg))
            else:
                arg_codes.append(self._convert_primitive(arg))

        return f"min({', '.join(arg_codes)})"

    def _convert_max(self, rule: Dict, context: str) -> str:
        """Convert max rule to max() call."""
        args = rule.get('args', [])

        arg_codes = []
        for arg in args:
            if isinstance(arg, dict):
                arg_codes.append(self._convert_rule(arg))
            else:
                arg_codes.append(self._convert_primitive(arg))

        return f"max({', '.join(arg_codes)})"

    def _convert_negate(self, rule: Dict, context: str) -> str:
        """Convert negate rule to Python negation."""
        value = rule.get('value', {})
        value_code = self._convert_rule(value)
        return f"-{value_code}"

    # -------------------------------------------------------------------------
    # String Formatting Converters
    # -------------------------------------------------------------------------

    def _convert_f_string(self, rule: Dict, context: str) -> str:
        """Convert f_string rule to Python f-string."""
        parts = rule.get('parts', [])

        result = 'f"'
        for part in parts:
            if isinstance(part, dict):
                part_type = part.get('type', '')
                if part_type == 'formatted_value':
                    value_code = self._convert_rule(part.get('value', {}))
                    result += f'{{{value_code}}}'
                elif part_type == 'constant':
                    result += str(part.get('value', ''))
                else:
                    value_code = self._convert_rule(part)
                    result += f'{{{value_code}}}'
            else:
                result += str(part)
        result += '"'

        return result

    def _convert_formatted_value(self, rule: Dict, context: str) -> str:
        """Convert formatted_value rule."""
        value = rule.get('value', {})
        return self._convert_rule(value)

    # -------------------------------------------------------------------------
    # Error/Unknown Converters
    # -------------------------------------------------------------------------

    def _convert_error(self, rule: Dict, context: str) -> str:
        """Convert error rule to comment."""
        message = rule.get('message', 'Unknown error')
        self.errors.append(f"Error rule encountered: {message}")
        return f"# Error: {message}"

    def _convert_unknown(self, rule: Dict, context: str) -> str:
        """Convert unknown rule to comment."""
        original = rule.get('original', rule)
        self.warnings.append(f"Unknown rule: {original}")
        return f"# Unknown: {original}"


